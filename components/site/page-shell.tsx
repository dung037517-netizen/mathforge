"use client";

import { FlaskConical } from "lucide-react";
import Link from "next/link";
import * as React from "react";

import { SiteHeader } from "@/components/site/site-header";
import { Button } from "@/components/ui/button";
import { progressStore } from "@/lib/practice/store";
import { useProgress } from "@/lib/practice/use-progress";
import { FINHUB_URL, REPOSITORY_URL, TRADEMARK_NOTICE } from "@/lib/site";
import { cn } from "@/lib/utils";

/** Shown on every page while the simulated student's data is on screen. */
function SampleBanner() {
  const { demo } = useProgress();
  if (!demo) return null;
  return (
    <div role="status" className="border-b border-warning/40 bg-warning/15">
      <div className="mx-auto flex max-w-[1200px] flex-wrap items-center gap-x-4 gap-y-2 px-4 py-2.5 text-sm sm:px-6">
        <FlaskConical className="size-4 shrink-0 text-warning" aria-hidden />
        <p className="min-w-0 flex-1">
          <strong className="font-semibold">Sample data.</strong> You are looking at a simulated student, generated to
          show what the reports look like. Nothing here is real usage, and nothing you do is saved.
        </p>
        <Button size="sm" variant="outline" onClick={() => progressStore.exitDemo()}>
          Exit sample data
        </Button>
      </div>
    </div>
  );
}

